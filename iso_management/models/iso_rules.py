"""Curated clause -> Odoo record mapping rules (the default "rules" provider).

Each rule says which Odoo model can support a clause, how to select the
relevant records, and why. Generic words are deliberately avoided: name
filters use specific terms (English and Indonesian). A clause with no rule is
reported as an honest gap, never as a coincidental keyword match.

strength:
  direct     the record type is itself the kind of record the clause asks for
  supporting the record shows the activity operating, but is not the record
             the clause literally requires
"""


def _any(field, terms):
    """OR-combine ilike conditions on one field."""
    domain = []
    for index, term in enumerate(terms):
        if index:
            domain.insert(0, "|")
        domain.append((field, "ilike", term))
    return domain


# Only attachments on business records that have an openable Odoo page.
_ATTACHABLE_MODELS = [
    "sale.order", "purchase.order", "account.move", "stock.picking", "crm.lead",
    "product.template", "product.product", "calendar.event", "account.bank.statement",
]
_NOT_ISO_FILES = [
    ("res_model", "in", _ATTACHABLE_MODELS),
    ("res_id", "!=", 0),
    ("res_field", "=", False),
    ("type", "=", "binary"),
]


def _file(terms):
    return _NOT_ISO_FILES + _any("name", terms)


def _rule(model, label, reason, strength="supporting", domain=None, date_field="create_date"):
    return {
        "model": model, "label": label, "reason": reason, "strength": strength,
        "domain": domain or [], "date_field": date_field,
    }


